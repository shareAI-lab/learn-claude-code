#!/usr/bin/env python3
# Harness（执行框架）: team mailboxes（团队邮箱）——多个模型通过文件协同。
"""
s15_agent_teams.py - Agent Teams（智能体团队）

具名持久智能体 + 文件化 JSONL 收件箱。
每个队友在独立线程运行自己的 agent loop，
通信通过 append-only 收件箱文件完成。

    子智能体（s04）生命周期：创建 -> 执行 -> 返回摘要 -> 销毁
    队友（s15）生命周期：创建 -> 工作 -> 空闲 -> 再工作 -> ... -> 关停

    配置文件 `.team/config.json` 保存队友身份与状态：
      {"team_name":"default","members":[{"name":"alice","role":"coder","status":"idle"}]}
    收件箱目录 `.team/inbox/` 为每位队友维护独立 JSONL 文件（如 `alice.jsonl`）。

    发送消息示例：
      send_message("alice", "fix bug") -> 以追加方式写入 `alice.jsonl`
    读取收件箱示例：
      read_inbox("alice") -> 读取全部消息后清空文件（drain）

    每个队友线程都运行自己的 agent_loop：
      status=working（工作中） -> status=idle（空闲） -> 等待下一条消息/任务

核心观点：队友具备“名字、收件箱、独立循环”三要素。

建议阅读顺序：
1. MessageBus：消息如何入队并被 drain（取空）。
2. TeammateManager：持久队友状态长什么样。
3. _teammate_loop / TOOL_HANDLERS：具名队友如何反复进入同一工具循环。

最常见混淆点：
- teammate（队友）不是 one-shot subagent（一次性子智能体）
- inbox message（收件箱消息）还不是完整 protocol request（协议请求）

教学边界：
本文件先讲“具名持久 worker + mailbox（邮箱）”。
审批协议与自治策略放在后续章节。
"""

